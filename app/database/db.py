
import json
import os
import sqlite3
from pathlib import Path
from threading import Lock
from typing import Any
from urllib.parse import urlparse, urlunparse
import psycopg
from psycopg.rows import dict_row


class EventDatabase:
    """Store RDRS events and incidents in SQLite or PostgreSQL."""

    INCIDENT_STATUSES = {
        "Open",
        "Investigating",
        "Resolved",
        "False Positive",
    }

    def __init__(self, database_path: str = "data/rdrs.db"):
        self.database_url = os.getenv("DATABASE_URL", "").strip()
        self.use_postgres = bool(self.database_url)

        self.lock = Lock()

        if self.use_postgres:
            # Normalize common PostgreSQL URI schemes.
            parsed = urlparse(self.database_url)
            if parsed.scheme in ("postgres", "postgresql"):
                self.database_url = urlunparse(
                    parsed._replace(scheme="postgresql")
                )
            else:
                raise ValueError("DATABASE_URL must be a PostgreSQL URI")

            self.path = None
        else:
            self.path = Path(database_path).resolve()
            self.path.parent.mkdir(parents=True, exist_ok=True)

        self._initialize()

    def _connect(self):
        if self.use_postgres:
            return psycopg.connect(
                self.database_url,
                row_factory=dict_row,
                connect_timeout=10,
            )

        connection = sqlite3.connect(self.path, timeout=10)
        connection.row_factory = sqlite3.Row
        return connection

    def _initialize(self):
        if self.use_postgres:
            id_type = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            event_id_type = "BIGINT"
            timestamp_type = "TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP"
            reasons_type = "JSONB NOT NULL"
        else:
            id_type = "INTEGER PRIMARY KEY AUTOINCREMENT"
            event_id_type = "INTEGER"
            timestamp_type = "TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP"
            reasons_type = "TEXT NOT NULL"

        with self._connect() as connection:
            connection.execute(f"""
                CREATE TABLE IF NOT EXISTS events (
                    id {id_type},
                    timestamp {timestamp_type},
                    path TEXT NOT NULL,
                    action TEXT NOT NULL,
                    entropy DOUBLE PRECISION,
                    risk_score INTEGER NOT NULL,
                    severity TEXT NOT NULL,
                    status TEXT NOT NULL,
                    reasons {reasons_type}
                )
            """)

            connection.execute(f"""
                CREATE TABLE IF NOT EXISTS incidents (
                    id {id_type},
                    event_id {event_id_type} NOT NULL UNIQUE
                        REFERENCES events(id),
                    status TEXT NOT NULL DEFAULT 'Open',
                    notes TEXT NOT NULL DEFAULT '',
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
            """)

    @staticmethod
    def _json_value(value):
        if isinstance(value, str):
            return json.loads(value)
        return value

    def add_event(self, event: dict[str, Any]) -> int:
        reasons = event.get("reasons", [])

        with self.lock, self._connect() as connection:
            if self.use_postgres:
                row = connection.execute("""
                    INSERT INTO events (
                        path, action, entropy, risk_score,
                        severity, status, reasons
                    ) VALUES (%s, %s, %s, %s, %s, %s, %s)
                    RETURNING id
                """, (
                    event["path"],
                    event["action"],
                    event.get("entropy"),
                    event["risk_score"],
                    event["severity"],
                    event["status"],
                    json.dumps(reasons),
                )).fetchone()
                event_id = int(row["id"])

                if event["risk_score"] >= 20:
                    connection.execute("""
                        INSERT INTO incidents (event_id)
                        VALUES (%s)
                        ON CONFLICT (event_id) DO NOTHING
                    """, (event_id,))
            else:
                cursor = connection.execute("""
                    INSERT INTO events (
                        path, action, entropy, risk_score,
                        severity, status, reasons
                    ) VALUES (?, ?, ?, ?, ?, ?, ?)
                """, (
                    event["path"],
                    event["action"],
                    event.get("entropy"),
                    event["risk_score"],
                    event["severity"],
                    event["status"],
                    json.dumps(reasons),
                ))
                event_id = int(cursor.lastrowid)

                if event["risk_score"] >= 20:
                    connection.execute("""
                        INSERT OR IGNORE INTO incidents (event_id)
                        VALUES (?)
                    """, (event_id,))

            return event_id

    def list_events(self, limit: int = 100) -> list[dict[str, Any]]:
        limit = max(1, min(limit, 1000))
        placeholder = "%s" if self.use_postgres else "?"

        with self._connect() as connection:
            rows = connection.execute(
                f"SELECT * FROM events ORDER BY id DESC LIMIT {placeholder}",
                (limit,),
            ).fetchall()

        results = []
        for row in rows:
            item = dict(row)
            item["reasons"] = self._json_value(item["reasons"])
            if hasattr(item.get("timestamp"), "isoformat"):
                item["timestamp"] = item["timestamp"].isoformat(sep=" ")
            results.append(item)

        return results

    def list_incidents(self, limit: int = 100) -> list[dict[str, Any]]:
        limit = max(1, min(limit, 1000))
        placeholder = "%s" if self.use_postgres else "?"

        with self._connect() as connection:
            rows = connection.execute(f"""
                SELECT
                    i.id AS incident_id,
                    i.status AS incident_status,
                    i.notes,
                    i.updated_at,
                    e.id AS event_id,
                    e.timestamp,
                    e.path,
                    e.action,
                    e.risk_score,
                    e.severity,
                    e.reasons
                FROM incidents i
                JOIN events e ON e.id = i.event_id
                ORDER BY i.id DESC
                LIMIT {placeholder}
            """, (limit,)).fetchall()

        results = []
        for row in rows:
            item = dict(row)
            item["reasons"] = self._json_value(item["reasons"])
            for field in ("timestamp", "updated_at"):
                if hasattr(item.get(field), "isoformat"):
                    item[field] = item[field].isoformat(sep=" ")
            results.append(item)

        return results

    def update_incident(
        self,
        incident_id: int,
        status: str,
        notes: str = "",
    ) -> dict[str, Any] | None:
        if status not in self.INCIDENT_STATUSES:
            raise ValueError(
                f"Invalid status. Choose one of: "
                f"{', '.join(sorted(self.INCIDENT_STATUSES))}"
            )

        placeholder = "%s" if self.use_postgres else "?"

        with self.lock, self._connect() as connection:
            cursor = connection.execute(f"""
                UPDATE incidents
                SET status = {placeholder},
                    notes = {placeholder},
                    updated_at = CURRENT_TIMESTAMP
                WHERE id = {placeholder}
            """, (status, notes, incident_id))

            if cursor.rowcount == 0:
                return None

            row = connection.execute(f"""
                SELECT * FROM incidents WHERE id = {placeholder}
            """, (incident_id,)).fetchone()

            result = dict(row)
            if hasattr(result.get("updated_at"), "isoformat"):
                result["updated_at"] = result["updated_at"].isoformat(sep=" ")
            return result
