import os
import sqlite3
from pathlib import Path
from urllib.parse import urlparse, urlunparse

import psycopg
from psycopg.rows import dict_row
from argon2 import PasswordHasher
from sqlite3 import IntegrityError as SQLiteIntegrityError
from psycopg.errors import UniqueViolation


class UserDatabase:
    def __init_hasher(self):
        self.hasher = PasswordHasher()
    """Persistent user accounts for RDRS."""

    def __init__(self, database_path="data/rdrs.db"):
        self.hasher = PasswordHasher()
        self.database_url = os.getenv("DATABASE_URL", "").strip()
        self.use_postgres = bool(self.database_url)

        if self.use_postgres:
            parsed = urlparse(self.database_url)
            if parsed.scheme not in ("postgres", "postgresql"):
                raise ValueError("DATABASE_URL must be PostgreSQL")
            self.database_url = urlunparse(
                parsed._replace(scheme="postgresql")
            )
            self.path = None
        else:
            self.path = Path(database_path).resolve()
            self.path.parent.mkdir(parents=True, exist_ok=True)

        self.initialize()

    def connect(self):
        if self.use_postgres:
            return psycopg.connect(
                self.database_url,
                row_factory=dict_row,
                connect_timeout=10,
            )

        conn = sqlite3.connect(self.path, timeout=10)
        conn.row_factory = sqlite3.Row
        return conn

    def initialize(self):
        id_type = (
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            if self.use_postgres
            else "INTEGER PRIMARY KEY AUTOINCREMENT"
        )

        with self.connect() as conn:
            conn.execute(f"""
                CREATE TABLE IF NOT EXISTS rdrs_users (
                    id {id_type},
                    full_name TEXT NOT NULL,
                    username TEXT NOT NULL UNIQUE,
                    email TEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
            """)

    def get_user(self, username):
        username = username.strip().lower()

        with self.connect() as conn:
            return conn.execute(
                "SELECT * FROM rdrs_users WHERE username = %s"
                if self.use_postgres
                else "SELECT * FROM rdrs_users WHERE username = ?",
                (username,),
            ).fetchone()

    def hash_password(self, password):
        return self.hasher.hash(password)

    def create_user(self, full_name, username, email, password_hash):
        full_name = full_name.strip()
        username = username.strip().lower()
        email = email.strip().lower()
        placeholder = "%s" if self.use_postgres else "?"

        try:
            with self.connect() as conn:
                conn.execute(
                    f"""
                    INSERT INTO rdrs_users
                        (full_name, username, email, password_hash)
                    VALUES ({placeholder}, {placeholder}, {placeholder}, {placeholder})
                    """,
                    (full_name, username, email, password_hash),
                )
            return True
        except (SQLiteIntegrityError, UniqueViolation):
            return False

    def find_by_email(self, email):
        email = email.strip().lower()
        placeholder = "%s" if self.use_postgres else "?"

        with self.connect() as conn:
            return conn.execute(
                f"SELECT * FROM rdrs_users WHERE email = {placeholder}",
                (email,),
            ).fetchone()


users_db = UserDatabase()
